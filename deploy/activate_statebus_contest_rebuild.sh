  export STATEBUS_CONTEST_PREFIX_FEEDBACK_ADAPTIVE="${STATEBUS_CONTEST_PREFIX_FEEDBACK_ADAPTIVE:-0}"
  export STATEBUS_PREFIX_POLICY="$STATEBUS_CONTEST_PREFIX_POLICY"
  export STATEBUS_PREFIX_ALIGNMENT_MODE="independent"
  export STATEBUS_PREFIX_LAYOUT_VERSION="${STATEBUS_PREFIX_LAYOUT_VERSION:-v2}"
  export STATEBUS_PREFIX_REQUIRE_EXCLUSIVE_METRICS="${STATEBUS_PREFIX_REQUIRE_EXCLUSIVE_METRICS:-true}"
