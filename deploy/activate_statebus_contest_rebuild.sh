  export STATEBUS_CONTEST_VLLM_START_SCRIPT="${STATEBUS_CONTEST_VLLM_START_SCRIPT:-$repo_root/scripts/start_vllm_qwen3_32b_latent.sh}"
  export STATEBUS_CONTEST_VLLM_MAX_LOGPROBS="${STATEBUS_CONTEST_VLLM_MAX_LOGPROBS:-20}"
