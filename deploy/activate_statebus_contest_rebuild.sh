  export STATEBUS_CONTEST_ALLOW_SERVICE_RESTART="${STATEBUS_CONTEST_ALLOW_SERVICE_RESTART:-0}"
  export STATEBUS_CONTEST_ALLOW_OPENEULER_VALIDATION="${STATEBUS_CONTEST_ALLOW_OPENEULER_VALIDATION:-0}"

  export STATEBUS_DOCKER_TARGET="${STATEBUS_DOCKER_TARGET:-core}"
  export STATEBUS_UID="${STATEBUS_UID:-$(id -u)}"
  export STATEBUS_GID="${STATEBUS_GID:-$(id -g)}"
  export STATEBUS_OPENEULER_RELEASE="${STATEBUS_OPENEULER_RELEASE:-24.03-lts-sp3}"
  export STATEBUS_OPENEULER_COMPOSE_FILE="${STATEBUS_OPENEULER_COMPOSE_FILE:-$repo_root/docker/compose.yaml}"
  export STATEBUS_OPENEULER_IMAGE="${STATEBUS_OPENEULER_IMAGE:-statebus-dev-openeuler:24.03-lts-sp3-core}"
  export STATEBUS_OPENEULER_VALIDATION_ROOT="${STATEBUS_OPENEULER_VALIDATION_ROOT:-$STATEBUS_CONTEST_RUN_ROOT/openeuler-final}"
  export STATEBUS_OPENEULER_VALIDATION_STATUS="${STATEBUS_OPENEULER_VALIDATION_STATUS:-pending}"

  mkdir -p \
    "$STATEBUS_CACHES_DIR" \
    "$STATEBUS_CONTEST_DATA_ROOT" \
    "$STATEBUS_CONTEST_RUN_ROOT" \
    "$STATEBUS_CONTEST_LOG_ROOT" \
    "$STATEBUS_FILING_DOWNLOAD_ROOT" \
    "$STATEBUS_FILING_CANONICAL_ROOT" \
    "$STATEBUS_FILING_PRIVATE_GOLD_ROOT" \
    "$STATEBUS_OPENEULER_VALIDATION_ROOT"

  export PYTHONPATH="$repo_root${PYTHONPATH:+:$PYTHONPATH}"

  echo "[statebus-contest] profile=$STATEBUS_CONTEST_PROFILE"
  echo "[statebus-contest] phase=$STATEBUS_CONTEST_PROFILE_PHASE"
  echo "[statebus-contest] llm_config=$STATEBUS_LLM_CONFIG_FILE"
  echo "[statebus-contest] base_url=$STATEBUS_LOCAL_VLLM_BASE_URL"
  echo "[statebus-contest] metrics_url=$STATEBUS_VLLM_METRICS_URL"
  echo "[statebus-contest] model_path=$STATEBUS_VLLM_MODEL_PATH"
  echo "[statebus-contest] run_root=$STATEBUS_CONTEST_RUN_ROOT"
  echo "[statebus-contest] policies=prefix:$STATEBUS_PREFIX_POLICY logit:$STATEBUS_LOGIT_POLICY latent:$STATEBUS_LATENT_MODE"
  echo "[statebus-contest] live actions remain disabled until separately authorized"
}

_STATEBUS_CONTEST_HAD_ERREXIT=0
_STATEBUS_CONTEST_HAD_NOUNSET=0
_STATEBUS_CONTEST_HAD_PIPEFAIL=0
if shopt -qo errexit; then
  _STATEBUS_CONTEST_HAD_ERREXIT=1
fi
if shopt -qo nounset; then
  _STATEBUS_CONTEST_HAD_NOUNSET=1
fi
if shopt -qo pipefail; then
  _STATEBUS_CONTEST_HAD_PIPEFAIL=1
fi

if _statebus_activate_contest_rebuild_main; then
  _statebus_contest_status=0
else
  _statebus_contest_status=$?
fi

_statebus_contest_restore_shell_options

unset -f _statebus_contest_restore_shell_options
unset -f _statebus_activate_contest_rebuild_main
unset _STATEBUS_CONTEST_HAD_ERREXIT _STATEBUS_CONTEST_HAD_NOUNSET _STATEBUS_CONTEST_HAD_PIPEFAIL

return "${_statebus_contest_status}" 2>/dev/null || exit "${_statebus_contest_status}"
