  export STATEBUS_FILING_MAX_ARCHIVE_BYTES="${STATEBUS_FILING_MAX_ARCHIVE_BYTES:-536870912}"

  export STATEBUS_CONTEST_PREFIX_POLICY="${STATEBUS_CONTEST_PREFIX_POLICY:-off}"
