  export STATEBUS_LOGIT_DECISION_TYPE="${STATEBUS_LOGIT_DECISION_TYPE:-executor_tool_recipe_choice_v1}"
  export STATEBUS_LOGIT_MAX_ACTIONS="${STATEBUS_LOGIT_MAX_ACTIONS:-1}"
  export STATEBUS_LOGIT_LEASE_MS="${STATEBUS_LOGIT_LEASE_MS:-30000}"
  export STATEBUS_LOGIT_STATE_POOL_MODE="${STATEBUS_LOGIT_STATE_POOL_MODE:-shared_memory}"

  # Latent/prompt-embedding/KV handoff is permanently excluded from this profile.
  export STATEBUS_LATENT_MODE="off"
  export STATEBUS_LATENT_HANDOFF_MODE="off"
  export STATEBUS_LATENT_PROMPT_EMBEDS_ENABLED="false"

  export STATEBUS_FORMAL_REQUEST_MODE="${STATEBUS_FORMAL_REQUEST_MODE:-serialized}"
  export STATEBUS_FORMAL_REQUEST_CONCURRENCY="${STATEBUS_FORMAL_REQUEST_CONCURRENCY:-1}"
  export STATEBUS_CONTEST_ALLOW_METRICS_CHECK="${STATEBUS_CONTEST_ALLOW_METRICS_CHECK:-0}"
  export STATEBUS_CONTEST_ALLOW_TOP_LOGPROBS_PROBE="${STATEBUS_CONTEST_ALLOW_TOP_LOGPROBS_PROBE:-0}"
  export STATEBUS_CONTEST_ALLOW_FILING_DOWNLOAD="${STATEBUS_CONTEST_ALLOW_FILING_DOWNLOAD:-0}"
  export STATEBUS_CONTEST_ALLOW_FORMAL_EXPERIMENTS="${STATEBUS_CONTEST_ALLOW_FORMAL_EXPERIMENTS:-0}"
